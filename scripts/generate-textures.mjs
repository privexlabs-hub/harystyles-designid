/**
 * Generates the grain tile as an inlineable data URI.
 *
 * Grain has to reach both renderers: the DOM preview can use a URL, but Satori
 * running in a worker resolves background images at render time and a fetch per
 * artboard would serialise the batch export. So the tile is kept deliberately
 * small — 64px, greyscale, palettised — and inlined into the bundle.
 */
import { writeFile, mkdir } from "node:fs/promises";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const TILE = 64;

// A deterministic value-noise field. Seeded by hand so the tile never changes
// between runs — a shifting texture would break the visual-regression baselines.
let seed = 0x2f6e2b1;
const rand = () => {
  seed ^= seed << 13;
  seed ^= seed >>> 17;
  seed ^= seed << 5;
  return ((seed >>> 0) % 1000) / 1000;
};

const pixels = Buffer.alloc(TILE * TILE * 2); // grey + alpha
for (let i = 0; i < TILE * TILE; i++) {
  const v = rand();
  pixels[i * 2] = Math.round(120 + v * 135);
  // Sparse and faint: grain should be felt, not seen.
  pixels[i * 2 + 1] = v > 0.55 ? Math.round(v * 46) : 0;
}

const png = await sharp(pixels, { raw: { width: TILE, height: TILE, channels: 2 } })
  .png({ palette: true, colours: 32, compressionLevel: 9 })
  .toBuffer();

await mkdir(join(ROOT, "public/assets/textures"), { recursive: true });
await writeFile(join(ROOT, "public/assets/textures/grain.png"), png);

const dataUri = `data:image/png;base64,${png.toString("base64")}`;

await writeFile(
  join(ROOT, "lib/templates/textures.ts"),
  `/**
 * Generated by scripts/generate-textures.mjs. Do not edit by hand.
 *
 * Inlined as a data URI because Satori resolves background images at render
 * time, and a network fetch per artboard would serialise the batch export.
 */

/** A ${TILE}px tiling grain, ${(png.length / 1024).toFixed(1)} KiB. */
export const GRAIN_TILE = ${JSON.stringify(dataUri)};

export const GRAIN_SIZE = ${TILE};
`,
);

console.log(`grain tile: ${(png.length / 1024).toFixed(1)} KiB → lib/templates/textures.ts`);
